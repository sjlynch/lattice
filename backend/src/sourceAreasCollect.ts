import fs from 'node:fs/promises';
import path from 'node:path';
import { collectSourceFiles } from './scanner/collectSourceTree.js';
import { loadGitignore } from './scanner/ignore.js';
import { canonicalProjectPath } from './projectPath.js';
import { isAreaSourceFile, type AreaFile } from './shared/sourceAreas.js';

const MANIFEST = /^(package\.json|pyproject\.toml|setup\.py|go\.mod|Cargo\.toml|pom\.xml|build\.gradle(?:\.kts)?|.+\.csproj|Gemfile|composer\.json|mix\.exs|pubspec\.yaml)$/;
const GENERATED = /@generated|do not edit|auto[- ]?generated|generated by|this file is (auto-?)?generated/i;

export async function collectAreaSourceFiles(project: string): Promise<{ files: AreaFile[]; packageRoots: string[] }> {
  const root = canonicalProjectPath(project);
  await fs.access(root);
  const scanned = await collectSourceFiles(root, await loadGitignore(root));
  const files: AreaFile[] = [];
  // Bound open files; each read is at most 512 KB.
  for (let i = 0; i < scanned.length; i += 32) {
    const batch = await Promise.all(scanned.slice(i, i + 32).map(async (absolute): Promise<AreaFile | null> => {
      const relative = path.relative(root, absolute).split(path.sep).join('/');
      if (!isAreaSourceFile(relative)) return null;
      try {
        const stat = await fs.stat(absolute);
        if (stat.size > 512 * 1024) return null;
        const bytes = await fs.readFile(absolute);
        if (bytes.length > 512 * 1024 || GENERATED.test(bytes.subarray(0, 1024).toString('utf8'))) return null;
        const text = bytes.toString('utf8');
        const lines = text ? text.split('\n').length - (text.endsWith('\n') ? 1 : 0) : 1;
        return { path: relative, weight: Math.max(1, Math.min(2000, lines)) };
      } catch { return null; } // Files may disappear during a scan.
    }));
    files.push(...batch.filter((f): f is AreaFile => f !== null));
  }
  const dirs = new Set<string>(['.']);
  for (const file of files) {
    const segments = file.path.split('/').slice(0, -1);
    for (let i = 1; i <= segments.length; i++) dirs.add(segments.slice(0, i).join('/'));
  }
  const packageRoots = ['.'];
  for (const dir of [...dirs].sort()) {
    if (dir === '.') continue;
    const entries = await fs.readdir(path.join(root, dir), { withFileTypes: true }).catch(() => []);
    if (entries.some((e) => e.isFile() && MANIFEST.test(e.name))) packageRoots.push(dir);
  }
  return { files: files.sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0), packageRoots };
}
