// All area consumers must use identical production/generated filters and weights.
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { collectAreaSourceFiles } from '../sourceAreasCollect.js';
import { withTempDir, writeLayout } from './helpers/tempDir.js';
test('collector skips generated headers/large files, counts capped lines and detects manifests', async () => {
  await withTempDir('area-collector-', async (project) => {
    const markers = ['package.json', 'pyproject.toml', 'setup.py', 'go.mod', 'Cargo.toml', 'pom.xml', 'build.gradle', 'build.gradle.kts', 'App.csproj', 'Gemfile', 'composer.json', 'mix.exs', 'pubspec.yaml'];
    await writeLayout(project, {
      '.gitignore': 'ignored/\n', 'ignored/a.ts': 'no', 'node_modules/p/a.ts': 'no', 'node_modules/p/package.json': '{}',
      'tests/a.ts': 'no', 'src/types.d.ts': 'no', 'src/empty.ts': '', 'src/lines.ts': 'a\nb\nc\n',
      'src/capped.ts': 'x\n'.repeat(3000), 'src/huge.ts': 'x'.repeat(512 * 1024 + 1),
      ...Object.fromEntries(['@generated', 'DO NOT EDIT', 'auto-generated', 'autogenerated', 'auto generated', 'generated by', 'this file is generated', 'this file is auto-generated'].map((header, i) => [`gen/g${i}.ts`, `// ${header}\nx\n`])),
      ...Object.fromEntries(markers.flatMap((marker, i) => [[`p${i}/${marker}`, '{}'], [`p${i}/src/main.ts`, 'x\ny']])),
      'examples/package.json': '{}', 'examples/main.ts': 'no',
    });
    const result = await collectAreaSourceFiles(project);
    assert.deepEqual(result.packageRoots.slice().sort(), ['.', ...markers.map((_, i) => `p${i}`)].sort());
    assert.equal(result.files.length, markers.length + 5);
    assert.equal(result.files.find((f) => f.path === 'src/empty.ts')?.weight, 1);
    assert.equal(result.files.find((f) => f.path === 'src/lines.ts')?.weight, 3);
    assert.equal(result.files.find((f) => f.path === 'src/capped.ts')?.weight, 2000);
  });
});
