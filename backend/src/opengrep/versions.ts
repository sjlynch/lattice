// The Sigstore identity every release asset must be signed under. Opengrep's
// binaries are produced by its GitHub Actions release workflow (keyless
// Fulcio certificates whose SAN is the workflow URL). Checked by the pin script.
export const OPENGREP_SIGNING_IDENTITY = {
  oidcIssuer: 'https://token.actions.githubusercontent.com',
  // The rolling-release workflow on main, or a tagged release workflow.
  identityRegexp:
    '^https://github\\.com/opengrep/opengrep/\\.github/workflows/[^@]+@refs/(heads/main|tags/v[0-9.]+)$',
} as const;

