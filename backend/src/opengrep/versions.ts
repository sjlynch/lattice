export type OpengrepAssetPin = {
  // Lower-case hex SHA-256 of the exact bytes GitHub served when pinned.
  sha256: string;
  // Byte length, checked against the download before the digest so a
  // truncated transfer fails fast with a size message rather than a hash one.
  bytes: number;
};

