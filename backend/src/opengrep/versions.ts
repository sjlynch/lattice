// The ONLY place third-party Opengrep material is named in the Lattice repo:
// a pinned engine version with per-asset SHA-256 digests, and the rule packs
// with their pinned commits and licences. Nothing here is a binary or a rule
// file — Lattice stays MIT because the engine (LGPL-2.1) and every rule pack are
// runtime downloads into `~/.lattice/opengrep/` made at the user's explicit
// click, executed as a separate process, never committed, bundled or
// redistributed (see ./CLAUDE.md, "Licence boundary").
//
// Bumping the engine: run `node scripts/opengrep-pin.mjs <tag>` from the repo
// root. It downloads every release asset, verifies each Sigstore signature with
// `cosign verify-blob` against the Opengrep release workflow identity below,
// and rewrites the block between the `<opengrep-pin:assets>` markers. It
// REFUSES to write digests it could not verify, so a user installing from these
// pins inherits the signature check the maintainer performed — without needing
// cosign themselves. Never edit the digest block by hand.

